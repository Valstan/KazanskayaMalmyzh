import type { Access } from 'payload'

import { readSessionFromRequest } from '../lib/auth/session'

// Доступ посетителя к своей записи — по `sub` из подписанной сессии, а не по
// ролям Payload и не по переданному полю.
//
// Почему не по токену ЕСА: токен проверяется РОВНО ОДИН раз — на входе (RS256,
// JWKS по `kid`), и дальше живёт подписанная сессия в httpOnly-cookie. Проверка
// токена на каждом запросе означала бы сеть в критическом пути каждой
// страницы — или кэш JWKS в процессе, который на холодном старте роняет сайт.
//
// ⚠️ Аудит #015 (08.10): раньше здесь брался `sub` из НЕПОДПИСАННОГО разбора
// токена — самокованная cookie с чужим `esaSub` открывала чужую запись. Сейчас
// подпись проверяется при входе, а cookie подписана HMAC'ом (PAYLOAD_SECRET) и
// лежит с префиксом `__Host-` (#285): подбросить её с поддомена нельзя.
//
// Возвращаем ТОЧНОЕ равенство по `esaSub`, а не `contains`/`like`: подстрока в
// фильтре — это ровно тот класс, где фильтр целиком не ловит и запрос молча
// уходит в «ничего не нашлось».
export const visitorsOwnRecord: Access = ({ req }) => {
  const session = readSessionFromRequest(req)
  if (!session) return false
  return {
    esaSub: {
      equals: session.sub,
    },
  }
}
